//! Shared fixtures for SCTP packet validation tests.

use super::sctp_packet_crc32c;

/// A 32-byte SCTP INIT packet with a little-endian CRC32c field.
pub(super) const SCTP_INIT_PACKET: [u8; 32] = [
    0x13, 0x88, 0x00, 0x50, 0x00, 0x00, 0x00, 0x00, 0x12, 0xF6, 0xF6, 0xE9, 0x01, 0x00, 0x00, 0x14,
    0xDE, 0xAD, 0xBE, 0xEF, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, 0x02, 0x71, 0x5B, 0x5A, 0x94,
];

pub(super) fn seal<const N: usize>(mut packet: [u8; N]) -> [u8; N] {
    let crc = sctp_packet_crc32c(&packet);
    packet[8..12].copy_from_slice(&crc.to_le_bytes());
    packet
}

pub(super) fn chunk_packet<const N: usize>(chunk: &[u8], verification_tag: u32) -> [u8; N] {
    assert!(chunk.len() <= N - 12, "chunk must fit packet");
    let mut packet = [0u8; N];
    packet[0..2].copy_from_slice(&0x1388u16.to_be_bytes());
    packet[2..4].copy_from_slice(&0x0050u16.to_be_bytes());
    packet[4..8].copy_from_slice(&verification_tag.to_be_bytes());
    packet[12..12 + chunk.len()].copy_from_slice(chunk);
    seal(packet)
}

